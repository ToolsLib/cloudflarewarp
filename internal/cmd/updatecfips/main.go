// Command updatecfips checks and refreshes the bundled Cloudflare proxy IP ranges.
package main

import (
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"net/netip"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"time"

	"github.com/BetterCorp/cloudflarewarp/ips"
)

const (
	cloudflareURL   = "https://api.cloudflare.com/client/v4/ips"
	snapshotPath    = "ips/ips.go"
	maxResponseSize = 1 << 20
)

func main() {
	write := flag.Bool("write", false, "update ips/ips.go after validating Cloudflare's ranges")
	flag.Parse()
	if flag.NArg() != 0 {
		flag.Usage()
		os.Exit(2)
	}

	client := &http.Client{
		Timeout: 15 * time.Second,
		CheckRedirect: func(*http.Request, []*http.Request) error {
			return http.ErrUseLastResponse
		},
	}
	message, err := update(client, cloudflareURL, snapshotPath, ips.CFIPs(), *write)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Println(message)
}

func update(client *http.Client, endpoint, path string, current []string, write bool) (string, error) {
	published, err := fetchRanges(client, endpoint)
	if err != nil {
		return "", fmt.Errorf("fetch Cloudflare IP ranges: %w", err)
	}

	changes := rangeChanges(current, published)
	if changes == "" {
		return "Bundled Cloudflare IP ranges are current.", nil
	}
	if !write {
		return "", fmt.Errorf("detected Cloudflare IP range drift:\n%s\nTo update the snapshot, run go run ./internal/cmd/updatecfips -write", changes)
	}
	if err := writeSnapshot(path, published); err != nil {
		return "", fmt.Errorf("update Cloudflare IP snapshot: %w", err)
	}
	return fmt.Sprintf("Updated %s:\n%s", path, changes), nil
}

func fetchRanges(client *http.Client, endpoint string) ([]string, error) {
	response, err := client.Get(endpoint)
	if err != nil {
		return nil, err
	}
	defer func() { _ = response.Body.Close() }()
	if response.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("unexpected HTTP status %s", response.Status)
	}

	body, err := io.ReadAll(io.LimitReader(response.Body, maxResponseSize+1))
	if err != nil {
		return nil, err
	}
	if len(body) > maxResponseSize {
		return nil, errors.New("response exceeds 1 MiB")
	}

	var payload struct {
		Success bool `json:"success"`
		Result  struct {
			IPv4 []string `json:"ipv4_cidrs"`
			IPv6 []string `json:"ipv6_cidrs"`
		} `json:"result"`
	}
	if err := json.Unmarshal(body, &payload); err != nil {
		return nil, fmt.Errorf("decode API response: %w", err)
	}
	if !payload.Success {
		return nil, errors.New("received an unsuccessful Cloudflare API response")
	}
	return validateRanges(payload.Result.IPv4, payload.Result.IPv6)
}

func validateRanges(ipv4, ipv6 []string) ([]string, error) {
	if len(ipv4) == 0 || len(ipv6) == 0 {
		return nil, errors.New("expected nonempty IPv4 and IPv6 lists")
	}

	prefixes := make([]string, 0, len(ipv4)+len(ipv6))
	seen := make(map[netip.Prefix]struct{}, cap(prefixes))
	for _, family := range []struct {
		name   string
		isIPv4 bool
		cidrs  []string
	}{
		{name: "IPv4", isIPv4: true, cidrs: ipv4},
		{name: "IPv6", cidrs: ipv6},
	} {
		for _, cidr := range family.cidrs {
			prefix, err := netip.ParsePrefix(cidr)
			if err != nil {
				return nil, fmt.Errorf("invalid %s CIDR %q: %w", family.name, cidr, err)
			}
			if prefix.Addr().Is4() != family.isIPv4 || prefix.Addr().Is4In6() {
				return nil, fmt.Errorf("CIDR %q has the wrong address family for the %s list", cidr, family.name)
			}
			if prefix.Bits() == 0 || prefix != prefix.Masked() {
				return nil, fmt.Errorf("CIDR %q must be a network prefix narrower than /0", cidr)
			}
			if _, exists := seen[prefix]; exists {
				return nil, fmt.Errorf("duplicate CIDR %q", cidr)
			}
			seen[prefix] = struct{}{}
			prefixes = append(prefixes, prefix.String())
		}
	}
	return prefixes, nil
}

func rangeChanges(current, published []string) string {
	var changes []string
	for _, cidr := range published {
		if !slices.Contains(current, cidr) {
			changes = append(changes, "+ "+cidr)
		}
	}
	for _, cidr := range current {
		if !slices.Contains(published, cidr) {
			changes = append(changes, "- "+cidr)
		}
	}
	slices.Sort(changes)
	return strings.Join(changes, "\n")
}

func writeSnapshot(path string, prefixes []string) error {
	var source strings.Builder
	source.WriteString(`// Code generated by go run ./internal/cmd/updatecfips -write. DO NOT EDIT.

// Package ips contains the bundled Cloudflare proxy IP ranges.
package ips

// CFIPs returns the bundled Cloudflare proxy IP ranges.
func CFIPs() []string {
	return []string{
`)
	for _, cidr := range prefixes {
		fmt.Fprintf(&source, "\t\t%q,\n", cidr)
	}
	source.WriteString("\t}\n}\n")
	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		return err
	}

	file, err := os.CreateTemp(filepath.Dir(path), ".cloudflare-ips-*.tmp")
	if err != nil {
		return err
	}
	defer func() { _ = os.Remove(file.Name()) }()
	if _, err := file.Write(formatted); err != nil {
		_ = file.Close()
		return err
	}
	if err := file.Close(); err != nil {
		return err
	}
	if err := os.Chmod(file.Name(), 0o644); err != nil {
		return err
	}
	return os.Rename(file.Name(), path)
}
