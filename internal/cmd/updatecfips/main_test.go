const (
	originalSnapshot = "existing snapshot\n"
	reorderedRanges  = `{"success":true,"result":{"ipv4_cidrs":["198.51.100.0/24","192.0.2.0/24"],"ipv6_cidrs":["2001:0DB8:0001::/48"]}}`
	changedRanges    = `{"success":true,"result":{"ipv4_cidrs":["198.51.100.0/24","203.0.113.0/24"],"ipv6_cidrs":["2001:0DB8:0002::/48"]}}`
	expectedDiff     = "+ 2001:db8:2::/48\n+ 203.0.113.0/24\n- 192.0.2.0/24\n- 2001:db8:1::/48"
)

func TestUpdateSnapshot(t *testing.T) {
	t.Run("equivalent ranges", func(t *testing.T) {
		message, snapshot, err := updateFixture(t, http.StatusOK, reorderedRanges, true)
		if err != nil || !strings.Contains(message, "are current") {
			t.Fatalf("message = %q, error = %v", message, err)
		}
		if snapshot != originalSnapshot {
			t.Fatalf("identical ranges rewrote the snapshot: %q", snapshot)
		}
	})

	t.Run("check reports drift without writing", func(t *testing.T) {
		_, snapshot, err := updateFixture(t, http.StatusOK, changedRanges, false)
		if err == nil || !strings.Contains(err.Error(), "Cloudflare IP range drift:\n"+expectedDiff) {
			t.Fatalf("expected a drift report with the changed CIDRs, got %v", err)
		}
		if snapshot != originalSnapshot {
			t.Fatalf("read-only check rewrote the snapshot: %q", snapshot)
		}
	})

	t.Run("write replaces snapshot with validated ranges", func(t *testing.T) {
		message, snapshot, err := updateFixture(t, http.StatusOK, changedRanges, true)
		if err != nil || !strings.Contains(message, expectedDiff) {
			t.Fatalf("message = %q, error = %v", message, err)
		}
		const want = `// Code generated by go run ./internal/cmd/updatecfips -write. DO NOT EDIT.

// Package ips contains the bundled Cloudflare proxy IP ranges.
package ips

// CFIPs returns the bundled Cloudflare proxy IP ranges.
func CFIPs() []string {
	return []string{
		"198.51.100.0/24",
		"203.0.113.0/24",
		"2001:db8:2::/48",
	}
}
`
		if snapshot != want {
			t.Fatalf("generated snapshot =\n%s\nwant\n%s", snapshot, want)
		}
	})
}

func TestUpdatePreservesSnapshotOnInvalidResponse(t *testing.T) {
	tests := []struct {
		name   string
		status int
		body   string
		detail string
	}{
		{
			name: "HTTP error", status: http.StatusServiceUnavailable,
			detail: "unexpected HTTP status 503",
		},
		{
			name: "API error", body: `{"success":false}`,
			detail: "unsuccessful Cloudflare API response",
		},
		{
			name: "incomplete JSON", body: `{"success":true,"result":`,
			detail: "decode API response",
		},
		{
			name: "missing IPv4 list", body: `{"success":true,"result":{"ipv6_cidrs":["2001:db8::/32"]}}`,
			detail: "expected nonempty IPv4 and IPv6 lists",
		},
		{
			name: "empty IPv6 list", body: `{"success":true,"result":{"ipv4_cidrs":["192.0.2.0/24"],"ipv6_cidrs":[]}}`,
			detail: "expected nonempty IPv4 and IPv6 lists",
		},
		{
			name: "invalid CIDR", body: `{"success":true,"result":{"ipv4_cidrs":["192.0.2.0/24"],"ipv6_cidrs":["unavailable"]}}`,
			detail: "invalid IPv6 CIDR",
		},
		{
			name: "wrong address family", body: `{"success":true,"result":{"ipv4_cidrs":["192.0.2.0/24"],"ipv6_cidrs":["198.51.100.0/24"]}}`,
			detail: "wrong address family",
		},
		{
			name: "mapped IPv6 address", body: `{"success":true,"result":{"ipv4_cidrs":["192.0.2.0/24"],"ipv6_cidrs":["::ffff:192.0.2.0/120"]}}`,
			detail: "wrong address family",
		},
		{
			name: "host bits", body: `{"success":true,"result":{"ipv4_cidrs":["192.0.2.1/24"],"ipv6_cidrs":["2001:db8::/32"]}}`,
			detail: "must be a network prefix",
		},
		{
			name: "default route", body: `{"success":true,"result":{"ipv4_cidrs":["0.0.0.0/0"],"ipv6_cidrs":["2001:db8::/32"]}}`,
			detail: "narrower than /0",
		},
		{
			name: "duplicate CIDR", body: `{"success":true,"result":{"ipv4_cidrs":["192.0.2.0/24"],"ipv6_cidrs":["2001:db8::/32","2001:0DB8::/32"]}}`,
			detail: "duplicate CIDR",
		},
		{
			name: "oversized body", body: strings.Repeat(" ", maxResponseSize+1),
			detail: "response exceeds 1 MiB",
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			status := test.status
			if status == 0 {
				status = http.StatusOK
			}
			_, snapshot, err := updateFixture(t, status, test.body, true)
			if err == nil || !strings.HasPrefix(err.Error(), "fetch Cloudflare IP ranges:") || !strings.Contains(err.Error(), test.detail) {
				t.Fatalf("expected a fetch error with %q, got %v", test.detail, err)
			}
			if snapshot != originalSnapshot {
				t.Fatalf("invalid data rewrote the snapshot: %q", snapshot)
			}
		})
	}
}

func updateFixture(t *testing.T, status int, body string, write bool) (string, string, error) {
	t.Helper()
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		w.WriteHeader(status)
		_, _ = io.WriteString(w, body)
	}))
	t.Cleanup(server.Close)

	path := filepath.Join(t.TempDir(), "ips.go")
	if err := os.WriteFile(path, []byte(originalSnapshot), 0o644); err != nil {
		t.Fatal(err)
	}
	current := []string{"192.0.2.0/24", "198.51.100.0/24", "2001:db8:1::/48"}
	message, updateErr := update(server.Client(), server.URL, path, current, write)
	snapshot, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return message, string(snapshot), updateErr
}
